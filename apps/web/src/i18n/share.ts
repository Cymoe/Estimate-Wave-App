export const SHARE: Record<Lang, typeof en> = { en, es };

/** A refusal from the server in the reader's language, or its message as sent. */
export function refusalText(err: unknown, lang: Lang, fallback: string): string {
  const reason = err && typeof err === 'object' && 'reason' in err ? (err as { reason?: string }).reason : undefined;
  if (reason && SHARE[lang].reasons[reason]) return SHARE[lang].reasons[reason];
  return err instanceof Error && err.message ? err.message : fallback;
}
