/** The county a town we know is in, else nothing. */
export function countyForTown(city: string | undefined): string | undefined {
  if (!city) return undefined;
  return TOWN_COUNTIES[city.trim().toLowerCase()];
}

/** "midland county" / "Midland" → "Midland"; unknown names come back as given, trimmed. */
export function normalizeCounty(value: string | undefined): string | undefined {
  const trimmed = value?.trim().replace(/\s+county$/i, "");
  if (!trimmed) return undefined;
  const match = TEXAS_COUNTIES.find(
    (c) => c.toLowerCase() === trimmed.toLowerCase(),
  );
  return match ?? trimmed;
}
